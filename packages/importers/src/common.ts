// Rules every importer shares (importers.md §1):
//
//   rule 3  skip memory-anywhere's own output (a marked file, or a managed block inside a file)
//   rule 4  redact on the PC before anything leaves it; an item that was nothing but a secret is dropped
//   rule 5  idempotency key = sha256(source_type ‖ source_item_id ‖ extractor_version ‖ ordinal);
//           a list item without an id uses its content_norm_hash as source_item_id
//
// `Collector` applies them while a source module walks its input, and keeps the report counts.

import { createHash } from "node:crypto";
import { contentNormHash } from "@memory-anywhere/contracts/normalize";
import { redact } from "@memory-anywhere/contracts/redact";
import type { Counts, EstimateInputs, ImportItemT, ImportResult, SourceType } from "./types.ts";

/**
 * Bumped when a parser changes what it emits for the same input, or the server's extractor changes
 * how it reads it, so a re-import after the change gets new keys instead of being taken for items
 * the store already recorded. 2: the server's `extract_import/2`.
 */
export const EXTRACTOR_VERSION = "importers-2";

/** Atomic content limit (ImportItem.content). */
export const MAX_ATOMIC_CHARS = 400;
/** One extractor message (ImportItem.messages[]). */
export const MAX_MESSAGE_CHARS = 4000;
/** Messages per extract item (ImportItem.messages). */
export const MAX_MESSAGES_PER_ITEM = 20;
const MAX_SECTION_HINT = 80;
const MAX_GROUP_ID = 200;

// ---- rule 3: own output

/** Any of these anywhere in a file marks it as written by memory-anywhere: the whole file is skipped. */
const FILE_MARKER = /generated by memory-anywhere/iu;
const BLOCK_BEGIN = /memory-anywhere:begin/iu;
const BLOCK_END = /memory-anywhere:end/iu;

export function hasMarker(text: string): boolean {
	return FILE_MARKER.test(text) || BLOCK_BEGIN.test(text);
}

export function isGeneratedFile(text: string): boolean {
	return FILE_MARKER.test(text);
}

/**
 * The text without memory-anywhere's managed blocks (the lines from `memory-anywhere:begin` to
 * `memory-anywhere:end`, both included; an unclosed block runs to the end), and how many it removed.
 */
export function stripManagedBlocks(text: string): { text: string; blocks: number } {
	const kept: string[] = [];
	let inside = false;
	let blocks = 0;
	for (const line of text.split(/\r?\n/u)) {
		if (!inside && BLOCK_BEGIN.test(line)) {
			inside = true;
			blocks++;
			continue;
		}
		if (inside) {
			if (BLOCK_END.test(line)) inside = false;
			continue;
		}
		kept.push(line);
	}
	return { text: kept.join("\n"), blocks };
}

// ---- rule 5: keys

export function itemKey(sourceType: SourceType, sourceItemId: string, ordinal: number): string {
	return createHash("sha256")
		.update([sourceType, sourceItemId, EXTRACTOR_VERSION, String(ordinal)].join("\u001f"), "utf8")
		.digest("hex");
}

export function sha256Hex(data: string | Uint8Array): string {
	return createHash("sha256").update(data).digest("hex");
}

// ---- text helpers

/** The text with every `[REDACTED:<type>]` marker removed. */
export function withoutRedactions(text: string): string {
	return text.replace(/\[REDACTED:[a-z0-9_]+\]/gu, "");
}

/** True when the text has at least one letter or digit. */
export function hasWords(text: string): boolean {
	return /[\p{L}\p{N}]/u.test(text);
}

/** Whitespace runs collapsed and trimmed; cut to `max` code points. */
export function clip(text: string, max: number): string {
	const cps = [...text.replace(/\s+/gu, " ").trim()];
	return cps.length <= max ? cps.join("") : cps.slice(0, max).join("").trimEnd();
}

/** A heading as a section hint: leading emoji and symbols dropped, at most 80 characters. */
export function sectionHint(heading: string): string | undefined {
	const h = clip(heading.replace(/^[^\p{L}\p{N}]+/u, ""), MAX_SECTION_HINT);
	return h === "" ? undefined : h;
}

/** A list bullet's marker removed: `- `, `* `, `• `, `1. `, `1) `, a task box `[ ]`, and a leading tag like `[stated]`. */
export function stripBullet(line: string): string {
	return line
		.trim()
		.replace(/^(?:[-*+•–]|\d{1,3}[.)])\s+/u, "")
		.replace(/^\[[ xX]\]\s+/u, "")
		.replace(/^\[[a-z][a-z _-]{0,20}\]\s*/iu, "")
		.trim();
}

export function isBullet(line: string): boolean {
	return /^\s*(?:[-*+•–]|\d{1,3}[.)])\s+\S/u.test(line);
}

const ABBREVIATIONS = new Set([
	"e.g",
	"i.e",
	"etc",
	"vs",
	"mr",
	"mrs",
	"ms",
	"dr",
	"st",
	"jr",
	"sr",
	"approx",
	"incl",
	"no",
	"fig",
	"cf",
]);

/**
 * Sentences of `text`: a break after `.`, `!` or `?` (and any closing quote or bracket) followed by
 * white space and a capital letter, digit or opening quote; common abbreviations do not end one.
 */
export function sentences(text: string): string[] {
	const out: string[] = [];
	let start = 0;
	for (const m of text.matchAll(/[.!?]+["'”’)\]]*\s+(?=["'“‘([]?[\p{Lu}\p{N}])/gu)) {
		const end = m.index + m[0].length;
		const before = text.slice(start, m.index + 1);
		const lastWord = /([\p{L}.]+)\.$/u.exec(before)?.[1]?.toLowerCase();
		if (lastWord && (ABBREVIATIONS.has(lastWord) || /^\p{L}$/u.test(lastWord))) continue;
		out.push(text.slice(start, end).trim());
		start = end;
	}
	out.push(text.slice(start).trim());
	return out.filter((s) => s !== "");
}

/** Pieces of at most `max` characters: whole sentences packed together, an over-long sentence cut at white space. */
export function packSentences(text: string, max: number): string[] {
	const out: string[] = [];
	let cur = "";
	const flush = (): void => {
		if (cur !== "") out.push(cur);
		cur = "";
	};
	for (const s of sentences(text)) {
		if (s.length > max) {
			flush();
			for (let rest = s; rest !== "";) {
				if (rest.length <= max) {
					cur = rest;
					break;
				}
				const cut = rest.lastIndexOf(" ", max);
				const at = cut > max / 2 ? cut : max;
				out.push(rest.slice(0, at).trim());
				rest = rest.slice(at).trim();
			}
			continue;
		}
		if (cur === "") cur = s;
		else if (cur.length + 1 + s.length <= max) cur = `${cur} ${s}`;
		else {
			flush();
			cur = s;
		}
	}
	flush();
	return out;
}

const MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"];

/** `Nov 9, 2026` or `November 9, 2026` → `2026-11-09`; anything else → undefined. */
export function parseMonthDayYear(text: string): string | undefined {
	const m = /^([A-Za-z]{3,9})\.? (\d{1,2}), (\d{4})$/u.exec(text.trim());
	if (!m) return undefined;
	const month = MONTHS.indexOf((m[1] ?? "").slice(0, 3).toLowerCase());
	if (month < 0) return undefined;
	return `${m[3]}-${String(month + 1).padStart(2, "0")}-${String(Number(m[2])).padStart(2, "0")}`;
}

export function isoDate(d: Date): string {
	return d.toISOString().slice(0, 10);
}

// ---- the collector

export interface ItemMeta {
	readonly section_hint?: string | undefined;
	readonly group_id?: string | undefined;
	readonly date?: string | undefined;
}

/**
 * How an atomic text becomes items: `long` keeps it whole when it fits in 400 characters and splits
 * it by sentence otherwise (vendor list lines, bullets); `sentences` always gives one item per
 * sentence (prose paragraphs of an owner-written file).
 */
export type AtomicSplit = "long" | "sentences";

function withMeta(meta: ItemMeta): Partial<ImportItemT> {
	return {
		...(meta.group_id ? { group_id: clip(meta.group_id, MAX_GROUP_ID) } : {}),
		...(meta.date ? { date: meta.date } : {}),
		...(meta.section_hint ? { section_hint: clip(meta.section_hint, MAX_SECTION_HINT) } : {}),
	};
}

/** Builds a source's items under rules 3–5 and keeps its report counts. */
export class Collector {
	readonly sourceType: SourceType;
	readonly counts: Counts = {};
	readonly #items: ImportItemT[] = [];
	readonly #keys = new Set<string>();
	#turns = 0;
	#chars = 0;

	constructor(sourceType: SourceType) {
		this.sourceType = sourceType;
	}

	count(reason: string, n = 1): void {
		if (n !== 0) this.counts[reason] = (this.counts[reason] ?? 0) + n;
	}

	/**
	 * Redacts `text`. Returns undefined, counted as `skipped_redacted`, when nothing but redaction
	 * markers and punctuation is left.
	 */
	redacted(text: string): string | undefined {
		const r = redact(text);
		if (r.types.length === 0) return text;
		this.count("secrets_redacted", r.types.length);
		if (!hasWords(withoutRedactions(r.text))) {
			this.count("skipped_redacted");
			return undefined;
		}
		return r.text;
	}

	/** One fact from a list line or a bullet (already without its bullet marker). */
	atomic(raw: string, meta: ItemMeta = {}, split: AtomicSplit = "long"): void {
		const text = raw.replace(/\s+/gu, " ").trim();
		if (!hasWords(text)) {
			this.count("skipped_empty");
			return;
		}
		if (hasMarker(text)) {
			this.count("skipped_marker");
			return;
		}
		const clean = this.redacted(text);
		if (clean === undefined) return;
		const sourceItemId = contentNormHash(clean);
		const pieces = split === "sentences" || clean.length > MAX_ATOMIC_CHARS ? sentences(clean) : [clean];
		if (pieces.length > 1 && split === "long") this.count("split_long_items");
		pieces.forEach((piece, ordinal) => {
			if (piece.length > MAX_ATOMIC_CHARS) {
				this.count("skipped_too_long");
				return;
			}
			if (!hasWords(withoutRedactions(piece))) {
				this.count("skipped_empty");
				return;
			}
			this.#push({
				key: itemKey(this.sourceType, sourceItemId, ordinal),
				source_item_id: sourceItemId,
				ordinal,
				mode: "atomic",
				content: piece,
				...withMeta(meta),
			});
			this.#chars += piece.length;
		});
	}

	/** One extraction item: up to 20 messages, each already redacted and at most 4,000 characters. */
	extract(sourceItemId: string, ordinal: number, messages: readonly string[], meta: ItemMeta = {}): void {
		if (messages.length === 0) return;
		this.#push({
			key: itemKey(this.sourceType, sourceItemId, ordinal),
			source_item_id: clip(sourceItemId, 200),
			ordinal,
			mode: "extract",
			messages: [...messages],
			...withMeta(meta),
		});
		this.#turns += messages.length;
		for (const m of messages) this.#chars += m.length;
	}

	#push(item: ImportItemT): void {
		if (this.#keys.has(item.key)) {
			this.count("skipped_duplicate");
			return;
		}
		this.#keys.add(item.key);
		this.#items.push(item);
	}

	result(): ImportResult {
		const estimate: EstimateInputs = { turns: this.#turns, chars: this.#chars, item_count: this.#items.length };
		this.counts["items"] = this.#items.length;
		return { source_type: this.sourceType, items: this.#items, counts: this.counts, estimate };
	}
}
