// The rules every importer shares (importers.md §1): own output skipped (3), redaction on the PC
// (4), stable keys (5); and the history filters of §3.

import { describe, expect, it } from "vitest";
import { contentNormHash } from "@memory-anywhere/contracts/normalize";
import { EXTRACTOR_VERSION, itemKey, packSentences, sentences, stripManagedBlocks } from "../src/common.ts";
import {
	importHistory,
	isQuotedOrCode,
	messagePieces,
	paragraphs,
	parseDateFlag,
	type Conversation,
} from "../src/history.ts";
import { runImporter, SOURCE_TYPES } from "../src/index.ts";
import { createHash } from "node:crypto";
import { file, fixture } from "./helpers.ts";

// Token-shaped values are assembled at run time so the source never holds a literal token.
const t = (...parts: string[]): string => parts.join("");
const GITHUB_TOKEN = t("ghp", "_0123456789abcdefghijABCDEFGHIJ012345");

describe("rule 3: memory-anywhere's own output is skipped", () => {
	it("skips a whole file marked as generated", () => {
		const r = runImporter("claude-user-md", [
			file("<!-- generated by memory-anywhere -->\n- Alex likes tea.\n", "CLAUDE.md"),
			file("- Alex likes coffee.\n", "rules/a.md"),
		]);
		expect(r.items.map((i) => i.content)).toEqual(["Alex likes coffee."]);
		expect(r.counts).toMatchObject({ files_read: 2, skipped_marker_files: 1 });
	});

	it("cuts managed blocks, also an unclosed one, and keeps the rest", () => {
		expect(
			stripManagedBlocks(
				"a\n<!-- memory-anywhere:begin -->\nb\n<!-- memory-anywhere:end -->\nc\n<!-- memory-anywhere:begin -->\nd",
			),
		).toEqual({ text: "a\nc", blocks: 2 });
	});

	it("skips a pasted list that carries a marker anywhere, and a chat message that carries one", () => {
		expect(
			runImporter("chatgpt-memory", [file("Alex likes tea.\nGenerated by memory-anywhere: Alex likes coffee.\n")])
				.counts,
		).toMatchObject({ items: 0, skipped_marker_files: 1 });
		const conv: Conversation = {
			id: "c",
			time: undefined,
			messages: [
				{ id: "1", author: "user", text: "Alex likes tea.", time: undefined },
				{ id: "2", author: "user", text: "memory-anywhere:begin profile", time: undefined },
			],
		};
		expect(importHistory("claude-history", [conv], {}).counts).toMatchObject({
			skipped_marker: 1,
			user_messages_kept: 1,
		});
	});
});

describe("rule 4: redaction before anything leaves the PC", () => {
	it("redacts a secret inside an item and drops an item that was only a secret", () => {
		const r = runImporter("chatgpt-memory", [
			file(`Alex's deploy token is ${GITHUB_TOKEN} for Orrery.\n${GITHUB_TOKEN}\n- ${GITHUB_TOKEN}.\n`),
		]);
		expect(r.items.map((i) => i.content)).toEqual(["Alex's deploy token is [REDACTED:github_token] for Orrery."]);
		expect(r.counts).toMatchObject({ secrets_redacted: 3, skipped_redacted: 2 });
		expect(JSON.stringify(r)).not.toContain(GITHUB_TOKEN);
	});

	it("redacts history messages and summary paragraphs too", () => {
		const conv: Conversation = {
			id: "c",
			time: undefined,
			messages: [
				{ id: "1", author: "user", text: `my card is 4111 1111 1111 1111, keep it`, time: undefined },
				{ id: "2", author: "user", text: "Alex likes tea.", time: undefined },
			],
		};
		const h = importHistory("chatgpt-history", [conv], {});
		expect(h.items[0]?.messages?.[0]).toBe("my card is [REDACTED:payment_card], keep it");
		const s = runImporter("gemini-memory-summary", [file(`Money\n\nAlex keeps ${GITHUB_TOKEN} in a notes file.\n`)]);
		expect(JSON.stringify(s)).not.toContain(GITHUB_TOKEN);
	});
});

describe("rule 5: idempotency keys", () => {
	it("is sha256(source_type ‖ source_item_id ‖ extractor_version ‖ ordinal)", () => {
		const expected = createHash("sha256")
			.update(["claude-memory", "abc", EXTRACTOR_VERSION, "2"].join("\u001f"))
			.digest("hex");
		expect(itemKey("claude-memory", "abc", 2)).toBe(expected);
		expect(itemKey("chatgpt-memory", "abc", 2)).not.toBe(expected);
	});

	it("uses the content_norm_hash as a list item's id, so case and trailing punctuation do not make a new item", () => {
		const [a] = runImporter("chatgpt-memory", [file("Alex likes tea.")]).items;
		const [b] = runImporter("chatgpt-memory", [file("  alex   LIKES tea  ")]).items;
		expect(a?.source_item_id).toBe(contentNormHash("Alex likes tea."));
		expect(b?.key).toBe(a?.key);
		const [edited] = runImporter("chatgpt-memory", [file("Alex likes green tea.")]).items;
		expect(edited?.key).not.toBe(a?.key);
	});

	it("gives the same keys for the same input, for every source", () => {
		const inputs = {
			"claude-memory": "claude-memory.txt",
			"chatgpt-memory": "chatgpt-memory.txt",
			"gemini-saved-info": "gemini-saved-info.txt",
			paste: "paste-grok.txt",
			"claude-user-md": "claude-user-md.md",
			"codex-user-md": "codex-user-md.md",
			"claude-code-auto-memory": "claude-code-auto-memory.prefers-pnpm.md",
			"codex-memories": "codex-memories.md",
			"chatgpt-history": "chatgpt-history.conversations.json",
			"claude-history": "claude-history.conversations.json",
			"chatgpt-memory-summary": "chatgpt-memory-summary.txt",
			"gemini-memory-summary": "gemini-memory-summary.txt",
			"gemini-history": "gemini-history.MyActivity.json",
		} as const;
		expect(Object.keys(inputs).sort()).toEqual([...SOURCE_TYPES].sort());
		for (const source of SOURCE_TYPES) {
			const run = (): string[] =>
				runImporter(source, [fixture(inputs[source])], { vendor: "grok" }).items.map((i) => i.key);
			const first = run();
			expect(first.length, source).toBeGreaterThan(0);
			expect(run(), source).toEqual(first);
			expect(new Set(first).size, source).toBe(first.length);
		}
	});

	it("counts a repeated line once", () => {
		expect(runImporter("chatgpt-memory", [file("Alex likes tea.\nAlex likes tea\n")]).counts).toMatchObject({
			items: 1,
			skipped_duplicate: 1,
		});
	});
});

describe("atomic size", () => {
	it("splits sentences, but not after abbreviations or initials", () => {
		expect(sentences("Alex uses e.g. Vim. Alex met J. Doe in 2020. Done! Next?")).toEqual([
			"Alex uses e.g. Vim.",
			"Alex met J. Doe in 2020.",
			"Done!",
			"Next?",
		]);
	});

	it("skips, with a count, a single sentence longer than 400 characters", () => {
		const r = runImporter("chatgpt-memory", [file(`Alex ${"really ".repeat(70)}likes tea. Alex likes coffee.`)]);
		expect(r.items.map((i) => [i.ordinal, i.content])).toEqual([[1, "Alex likes coffee."]]);
		expect(r.counts["skipped_too_long"]).toBe(1);
	});

	it("packs sentences into pieces of at most the limit, cutting an over-long one at a space", () => {
		const pieces = packSentences(`${"word ".repeat(30)}end. Short one. Another short one.`, 60);
		expect(pieces.every((p) => p.length <= 60)).toBe(true);
		expect(pieces.join(" ").replace(/\s+/gu, " ")).toBe(
			`${"word ".repeat(30)}end. Short one. Another short one.`.replace(/\s+/gu, " "),
		);
	});
});

describe("history filters (importers.md §3)", () => {
	const msg = (id: string, text: string, iso?: string, author: "user" | "other" = "user") => ({
		id,
		author,
		text,
		time: iso ? new Date(iso) : undefined,
	});
	const conv = (id: string, ...messages: ReturnType<typeof msg>[]): Conversation => ({
		id,
		time: new Date("2026-01-01T00:00:00Z"),
		messages,
	});

	it("keeps --since/--until (dates are whole days) and applies the minimum user turns inside the window", () => {
		const c = conv(
			"c1",
			msg("1", "Alex likes tea.", "2026-03-01T10:00:00Z"),
			msg("2", "Alex likes jazz.", "2026-03-31T23:00:00Z"),
			msg("3", "Alex likes chess.", "2026-04-01T00:00:01Z"),
		);
		const r = importHistory("claude-history", [c], {
			since: parseDateFlag("2026-03-01", "start"),
			until: parseDateFlag("2026-03-31", "end"),
		});
		expect(r.items[0]?.messages).toEqual(["Alex likes tea.", "Alex likes jazz."]);
		expect(r.counts["skipped_outside_dates"]).toBe(1);
		const strict = importHistory("claude-history", [c], {
			since: parseDateFlag("2026-03-15", "start"),
			until: parseDateFlag("2026-03-31", "end"),
		});
		expect(strict.items).toHaveLength(0);
		expect(strict.counts).toMatchObject({
			skipped_few_user_turns_conversations: 1,
			skipped_few_user_turns_messages: 1,
		});
		expect(importHistory("claude-history", [c], { conversationMinUserTurns: 4 }).items).toHaveLength(0);
		expect(
			importHistory("claude-history", [c], { conversationMinUserTurns: 1, since: parseDateFlag("2026-03-15", "start") })
				.items,
		).toHaveLength(1);
	});

	it("falls back to the conversation's time for an undated message", () => {
		const c = conv("c1", msg("1", "Alex likes tea."), msg("2", "Alex likes jazz."));
		expect(importHistory("claude-history", [c], { since: parseDateFlag("2025-12-01", "start") }).items[0]?.date).toBe(
			"2026-01-01T00:00:00.000Z",
		);
		expect(importHistory("claude-history", [c], { since: parseDateFlag("2026-02-01", "start") }).items).toHaveLength(0);
	});

	it("rejects a date it cannot read", () => {
		expect(() => parseDateFlag("last tuesday", "start")).toThrow(/not a date/u);
		expect(parseDateFlag(undefined, "start")).toBeUndefined();
	});

	it("batches at most 20 pieces per item, each dated by its first message", () => {
		const many = Array.from({ length: 45 }, (_, i) =>
			msg(`m${i}`, `Alex fact ${i}.`, new Date(Date.UTC(2026, 0, 1, 0, i)).toISOString()),
		);
		const r = importHistory("chatgpt-history", [conv("c9", ...many)], {});
		expect(r.items.map((i) => i.messages?.length)).toEqual([20, 20, 5]);
		expect(r.items.map((i) => i.date)).toEqual([
			"2026-01-01T00:00:00.000Z",
			"2026-01-01T00:20:00.000Z",
			"2026-01-01T00:40:00.000Z",
		]);
		expect(r.items.map((i) => i.source_item_id)).toEqual(["c9:m0", "c9:m20", "c9:m40"]);
		expect(r.items.every((i) => i.group_id === "c9")).toBe(true);
	});

	it("only splits a message over 4,000 characters; a short one keeps its code", () => {
		const short = "Look:\n\n```\nconst a = 1;\n```";
		expect(messagePieces(short)).toEqual({ pieces: [short], dropped: 0 });
		const quoted = Array.from({ length: 10 }, (_, i) => (i < 8 ? `> quoted ${i}` : `own line ${i}`)).join("\n");
		expect(isQuotedOrCode(quoted)).toBe(true);
		expect(isQuotedOrCode(quoted.replace(/> quoted [0-2]/gu, "own"))).toBe(false);
		const long = `Alex wrote this part.\n\n${quoted}\n\n\`\`\`\n${"x = 1\n\n".repeat(700)}\`\`\`\n\nAnd this part.`;
		expect(paragraphs(long).filter((p) => p.startsWith("```"))).toHaveLength(1);
		expect(messagePieces(long)).toEqual({ pieces: ["Alex wrote this part.", "And this part."], dropped: 2 });
	});
});
